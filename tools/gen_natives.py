"""Generate src/natives.h from alloc8or's rdr3-nativedb-data natives.json.

Usage: python3 tools/gen_natives.py path/to/natives.json > src/natives.h
The list of natives to wrap lives in tools/natives.txt.
"""
import json
import os
import sys

TYPES = {
    "void": "void", "int": "int", "BOOL": "BOOL", "float": "float", "Hash": "Hash",
    "Any": "int", "Entity": "Entity", "Ped": "Ped", "Player": "Player", "Object": "Object",
    "Vehicle": "Vehicle", "Blip": "Blip", "Vector3": "Vector3", "const char*": "const char*",
    "Any*": "int*", "Entity*": "Entity*", "Ped*": "Ped*", "Object*": "Object*", "Blip*": "Blip*", "Vehicle*": "Vehicle*",
    "float*": "float*", "Hash*": "Hash*", "int*": "int*",
}

here = os.path.dirname(os.path.abspath(__file__))
wanted = open(os.path.join(here, "natives.txt")).read().split()
db = json.load(open(sys.argv[1]))
found = {}
for ns, fns in db.items():
    for h, f in fns.items():
        if f["name"] in wanted and f["name"] not in found:
            found[f["name"]] = (ns, h, f)

missing = [w for w in wanted if w not in found]
if missing:
    sys.exit("missing natives: " + ", ".join(missing))

print("// Generated by tools/gen_natives.py. Do not edit by hand.")
print("#pragma once")
print('#include "scripthook.h"\n')
for name in wanted:
    ns, h, f = found[name]
    ret = TYPES[f["return_type"]]
    params = [(TYPES[p["type"]], p["name"]) for p in f["params"]]
    sig = ", ".join(f"{t} {n}" for t, n in params)
    args = "".join(f", {n}" for _, n in params)
    fn = name.lstrip("_")
    print(f"inline {ret} {fn}({sig}) {{ return invoke<{ret}>({h}ULL{args}); }}  // {ns}")
